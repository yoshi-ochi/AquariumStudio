/** 採取地の水域：'sea' 海・'river' 川・'lake' 湖 */
export const waterOf = (dest) => dest?.water ?? 'sea';

/** 漁法。川・湖（water が 'sea' 以外）では、川用の内容がある漁法はそれに置き換わる（river: true がつく） */
export function getMethod(id, water = 'sea') {
  const base = METHODS.find((x) => x.id === id);
  return base && water !== 'sea' && RIVER_METHODS[id] ? { ...base, ...RIVER_METHODS[id], river: true } : base;
}

