/** その採取地で使える漁法と、それぞれで捕れる生き物 */
export function methodsAt(dest) {
  return METHODS.map((method) => ({ method, catches: dest.pool.filter((id) => SPECIES_METHODS[id]?.includes(method.id)) })).filter((x) => x.catches.length);
}
