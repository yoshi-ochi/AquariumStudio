/** その採取地で使える漁法と、それぞれで捕れる生き物 */
export function methodsAt(dest) {
  return METHODS.map((base) => ({ method: getMethod(base.id, waterOf(dest)), catches: dest.pool.filter((id) => SPECIES_METHODS[id]?.includes(base.id)) })).filter((x) => x.catches.length);
}
